CREATE TABLE IF NOT EXISTS characters (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  title VARCHAR(255) DEFAULT NULL,
  class VARCHAR(100) DEFAULT NULL,
  birthday DATE DEFAULT NULL,
  photo VARCHAR(255) DEFAULT NULL,
  strength TINYINT NOT NULL DEFAULT 1,
  dexterity TINYINT NOT NULL DEFAULT 1,
  intellect TINYINT NOT NULL DEFAULT 1,
  charisma TINYINT NOT NULL DEFAULT 1,
  chaos TINYINT NOT NULL DEFAULT 1,
  resolve TINYINT NOT NULL DEFAULT 1,
  unique_trait_name VARCHAR(255) DEFAULT NULL,
  unique_trait_desc TEXT DEFAULT NULL,
  passive_ability_name VARCHAR(255) DEFAULT NULL,
  passive_ability_desc TEXT DEFAULT NULL,
  weakness VARCHAR(255) DEFAULT NULL,
  lore TEXT DEFAULT NULL,
  status VARCHAR(255) DEFAULT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  destination_slug VARCHAR(255) NOT NULL DEFAULT 'the-hearth',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
